const log = []
const ok = (name, cond, extra = '') => { log.push(`${cond ? 'PASS' : 'FAIL'}  ${name} ${extra}`); if (!cond) process.exitCode = 1 }

const AXE = require.resolve('axe-core/axe.min.js')
async function scan(name) {
  await page.waitForFunction(() => document.getAnimations().every((a) => a.playState !== 'running'), null, { timeout: 5000 }).catch(() => {}) // dialogs fade in; scan the settled page
  await page.addScriptTag({ path: AXE })
  const result = await page.evaluate(() => window.axe.run(document, { resultTypes: ['violations'] }))
  const bad = result.violations.filter((v) => v.impact === 'serious' || v.impact === 'critical')
  ok(`accessibility (axe): ${name}`, bad.length === 0, bad.map((v) => `${v.id} x${v.nodes.length}: ${v.nodes[0].html.slice(0, 90)} | ${v.nodes[0].any[0]?.message ?? ''}`).join('; '))
}
const shot = (n) => (SHOTS ? page.screenshot({ path: `${SHOTS}/${n}.png`, fullPage: true }) : Promise.resolve())
const iso = (offset) => { const d = new Date(); d.setDate(d.getDate() + offset); return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}` }
const pdfOf = async (download) => (await readFile(await download.path())).toString('latin1').replace(/\\([()])/g, '$1')
const csvOf = async (download) => (await readFile(await download.path(), 'utf8')).replace(/^\uFEFF/, '').split('\r\n')
const searchBox = () => page.getByRole('combobox', { name: 'Search projects, people, tasks' })
const projectLink = (n) => page.getByRole('link', { name: n, exact: true }).first()
const projectNames = () => page.locator('main a[href^="/projects/"]').allInnerTexts()
const homeReady = () => page.locator('main a[href^="/projects/"]').first().waitFor()
const more = async (item) => { await page.getByRole('button', { name: 'More' }).first().click(); await page.getByRole('menuitem', { name: item }).click() }
const menuOf = async (milestone, item) => { await page.getByRole('button', { name: `Milestone actions: ${milestone}` }).click(); await page.getByRole('menuitem', { name: item }).click() }
const tab = (name) => page.getByRole('tab', { name }).click()
const card = (name) => page.locator('div.MuiPaper-root').filter({ has: page.getByRole('heading', { name, exact: true }) }).last()

async function signIn(u, p) {
  await page.goto(URL + '/login')
  await page.getByLabel('Username').fill(u); await page.getByLabel(/^Password/).fill(p)
  await page.getByRole('button', { name: 'Sign in' }).click()
}
async function signOut() { await page.getByRole('button', { name: 'Account menu' }).click(); await page.getByRole('menuitem', { name: 'Sign out' }).click(); await page.waitForURL('**/login') }

